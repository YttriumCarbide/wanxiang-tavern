export function createBookshelf(context) {
  function targetTab(action) {
    return (
      {
        archives: 'npcs',
        records: 'records',
        memory: 'memory',
        manual: 'manual',
      }[action] || 'manual'
    );
  }
  return {
    open(action) {
      if (context.session.runtime.mode !== 'inn') return;
      if (action === 'memory' && context.memory?.open) {
        void context.memory.open();
        return;
      }
      context.records?.openTab?.(targetTab(action));
    },
    dispose() {},
  };
}
