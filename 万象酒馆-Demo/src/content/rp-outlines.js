export function rpChapterDirection(exploration) {
  if (!exploration || exploration.world || exploration.sequence >= 6) return '';
  const chapter = RP_CHAPTERS[exploration.map]?.[exploration.sequence || 0];
  if (!chapter) return '';
  const [scene, main, optional, atmosphere] = chapter;
  return `【第四节点RP改编 v48】\n本段优先按“${scene}”安排自由RP，取代旧大纲在此处的强制战斗和紧急追逐。主目标只表达结果：${main}。可选方向：${optional}。场景概览素材：${atmosphere}\n保留前后官设事实、Boss与人物出场顺序，调整其间节奏；开场只开启情境，不代替玩家完成交涉或决定解法。线索用途不要直接讲破，不生成操作攻略。第二节点可从当地人物、旅途小发现或小取舍设计，不必紧迫。`;
}
