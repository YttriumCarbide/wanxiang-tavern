const hit = (value) => ({ type: 'damage', value });
const buff = (key, value, target = 'opponents') => ({ type: 'buff', buff: key, value, target });
const move = (name, text, effects, extra = {}) => ({ name, text, slot: 1, effects, ...extra });
function enemy(
  id,
  name,
  hp,
  speed,
  portrait,
  description,
  intents,
  tactic = { target: 'exposed' },
) {
  const appearance = id.replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase());
  return {
    id,
    name,
    hp,
    speed,
    portrait: appearance,
    model: appearance + '.glb',
    designBase: portrait,
    description,
    intents,
    tactic,
    mp: 0,
    limit: 1,
    buffs: {},
    color: '#93c9da',
    title: '霜晶矿窟 / ' + name,
    attackStyle: 'stone-slam',
  };
}
function boss(...args) {
  return { ...enemy(...args), boss: true, phaseMode: 'cycle' };
}
