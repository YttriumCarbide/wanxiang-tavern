export function monsterWorldbook(id, name) {
  const lore = MONSTER_LORE[id];
  if (!lore) throw Error(`缺少怪物设定：${id}`);
  return [
    `名称：${name}`,
    `外形：${lore.appearance}`,
    `习性与能力：${lore.habits}`,
    `行动方式：${lore.motion}`,
    '叙事边界：这些是可观察特征与可能的行动。实际伤害、技能使用、受伤和胜负以游戏已经确认的事件为准。',
  ].join('\n');
}
